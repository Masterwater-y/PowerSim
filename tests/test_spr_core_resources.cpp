#include "fastsim/spr_core_resources.hpp"
#include <cassert>
#include <iostream>
using namespace fastsim;
int main() {
    SprIqProfile profile{{1, 1, 1}};
    SprPartitionedIq iq(profile);
    auto a = iq.acquire("IntAlu", true, false);
    assert(a && iq.used(SprIqDomain::Execution) == 1);
    assert(!iq.acquire("IntMult", true, false));
    auto m = iq.acquire("MemRead", true, true);
    auto s = iq.acquire("X86StoreData", true, false);
    assert(m && s && !iq.acquire("MemWrite", true, true));
    assert(!iq.acquire("IntAlu", false, false));
    auto follower = iq.join(*a, "IntAlu", false);
    assert(follower && iq.used(SprIqDomain::Execution) == 1);
    assert(!iq.join(*a, "MemRead", true));
    assert(!iq.release(*m, SprIqRelease::Issue));
    assert(iq.release(*a, SprIqRelease::Issue));
    assert(!iq.release(*a, SprIqRelease::Issue));
    assert(iq.used(SprIqDomain::Execution) == 1);
    assert(iq.release(*follower, SprIqRelease::Issue));
    auto replacement = iq.acquire("IntAlu", true, false);
    assert(replacement && !iq.release(*a, SprIqRelease::Issue));
    assert(iq.used(SprIqDomain::Execution) == 1);
    assert(iq.release(*m, SprIqRelease::Complete));
    assert(iq.release(*s, SprIqRelease::Issue));
    assert(iq.release(*replacement, SprIqRelease::Issue));
    assert(iq.used(SprIqDomain::Memory) == 0 && iq.used(SprIqDomain::StoreData) == 0);
    auto delayed = iq.acquire("SimdStridedLoad", true, true);
    assert(delayed && iq.used(SprIqDomain::Memory) == 1);
    assert(!iq.schedule_release(*delayed, SprIqRelease::Issue, 20));
    assert(iq.schedule_release(*delayed, SprIqRelease::Complete, 20));
    iq.advance(19);
    assert(iq.used(SprIqDomain::Memory) == 1);
    iq.advance(20);
    assert(iq.used(SprIqDomain::Memory) == 0);
    assert(!iq.schedule_release(*delayed, SprIqRelease::Complete, 21));
    auto early = iq.acquire("IntAlu", true, false);
    assert(early && iq.schedule_release(*early, SprIqRelease::Issue, 40));
    assert(iq.release(*early, SprIqRelease::Issue));
    auto reused = iq.acquire("IntAlu", true, false);
    assert(reused);
    iq.advance(40);
    assert(iq.used(SprIqDomain::Execution) == 1);
    assert(iq.release(*reused, SprIqRelease::Issue));
    SprPartitionedIq native(SprIqProfile{{128,72,48}});
    for (unsigned i = 0; i < 128; ++i) assert(native.acquire("IntAlu", true, false));
    assert(!native.acquire("IntAlu", true, false));
    for (unsigned i = 0; i < 72; ++i) assert(native.acquire("MemRead", true, true));
    assert(!native.acquire("MemRead", true, true));
    for (unsigned i = 0; i < 48; ++i) assert(native.acquire("X86StoreData", true, false));
    assert(!native.acquire("X86StoreData", true, false));
    assert(SprPartitionedIq::domain_for("InstPrefetch") == SprIqDomain::Execution);
    assert(SprPartitionedIq::domain_for("SimdStrideSegmentedStore") == SprIqDomain::Memory);
    SprPortRoundRobin rr;
    const std::uint16_t mask = (1u << 0) | (1u << 6);
    assert(rr.probe(1, mask, mask) == 0);
    assert(rr.probe(1, mask, 0) == -1);
    assert(rr.probe(1, mask, mask) == 0);
    assert(!rr.commit(1, mask, 5));
    assert(rr.probe(1, mask, mask) == 0);
    assert(rr.commit(1, mask, 0));
    assert(rr.probe(1, mask, mask) == 6);
    assert(rr.probe(2, mask, mask) == 0);
    assert(rr.probe(1, 1u << 6, 1u << 6) == 6);
    SprGenericFuRing ring;
    assert(ring.probe(mask, mask) == 0);
    assert(ring.commit(mask, 0));
    assert(ring.probe(mask, mask) == 6);
    SprGenericFuRing attempted_ring;
    assert(attempted_ring.attempt(mask, 0) == -1);
    assert(attempted_ring.attempt(mask, mask) == 6);
    assert(attempted_ring.attempt(mask, 1u << 6) == 6);
    assert(attempted_ring.attempt(mask, mask) == 0);
    SprLoadBanks banks;
    SprLoadBankRequest load{0x100, true, false, false};
    assert(banks.available(10, load));
    assert(banks.note_send(10, load, false));
    assert(banks.note_send(10, load, true));
    assert(banks.note_send(10, load, true));
    assert(!banks.available(10, load));
    assert(!banks.note_send(10, load, true));
    SprLoadBankRequest other{0x104, true, false, false};
    assert(banks.available(10, other));
    SprLoadBankRequest strict{0x100, true, true, false};
    assert(banks.available(10, strict) && banks.note_send(10, strict, true));
    SprLoadBankRequest prefetch{0x100, true, false, true};
    assert(banks.available(10, prefetch) && banks.note_send(10, prefetch, true));
    assert(banks.available(11, load));
    std::cout << "SPR core resource tests passed\n";
}
